<?php

namespace App\Http\Controllers\Api\Auth;

use App\Http\Controllers\Controller;
use App\Http\Requests\Auth\TenantRegisterRequest;
use App\Http\Resources\Auth\TenantRegisterResource;
use App\Models\Tenant;
use App\Models\User;
use Illuminate\Http\JsonResponse;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Hash;
use Spatie\Permission\Models\Role;

class TenantRegisterController extends Controller
{
    /**
     * Submit a new venue partner registration application.
     * Tenant status is set to 'pending' until Super Admin approves.
     */
    public function register(TenantRegisterRequest $request): JsonResponse
    {
        return DB::transaction(function () use ($request) {
            // 1. Create the venue (tenant) - slug is automatically generated by spatie/laravel-sluggable
            $tenant = Tenant::create([
                'name'           => $request->name,
                'company_name'   => $request->company_name,
                'phone'          => $request->phone,
                'city'           => $request->city,
                'address'        => $request->address,
                'description'    => $request->description,
                'latitude'       => $request->latitude,
                'longitude'      => $request->longitude,
                'preferred_plan' => $request->preferred_plan,
                'status'         => 'pending',
            ]);

            // 2. Create the venue owner user account (inactive until approved)
            $owner = User::create([
                'tenant_id' => $tenant->id,
                'name'      => $request->owner_name,
                'phone'     => $request->owner_phone,
                'email'     => $request->owner_email,
                'password'  => Hash::make($request->owner_password),
                'status'    => 'inactive',
            ]);

            // 3. Assign tenant_owner role
            $ownerRole = Role::firstOrCreate(['name' => 'tenant_owner']);
            $owner->assignRole($ownerRole);

            // 4. Link owner to tenant
            $tenant->update(['owner_id' => $owner->id]);

            // 5. Handle logo upload if provided
            if ($request->hasFile('logo')) {
                $tenant->addMedia($request->file('logo'))->toMediaCollection('logo');
            }

            return response()->json([
                'success' => true,
                'message' => 'Venue application submitted successfully. Your application is under review.',
                'data'    => new TenantRegisterResource($tenant->fresh()->load('owner')),
            ], 201);
        });
    }
}
